"""Write the Android :translate parity goldens from the real server functions.

Each golden records what the server code actually returns for a hand-written
input list, so the Kotlin ports in android/translate are checked against the
server, not against a re-implementation of it (D007). No network, no API key,
no server code is modified.

Inputs:  android/translate/src/test/resources/golden/inputs/*.json
Outputs: android/translate/src/test/resources/golden/
    parse.json           Translator._parse_response -> model_dump() or {"invalid": true}
    passthrough.json     _is_passthrough(source, translated, direction)
    extract.json         _extract_field and _extract_raw_translation
    request_bodies.json  _openai_request_body for every shared/models.json model + extras
    prompts.json         prompt builders ("Speaker A") and the passthrough-retry prompt
    idioms.json          IdiomScanner.scan + PipelineOrchestrator._merge_idioms
    direction.json       PipelineOrchestrator._resolve_effective_direction
    costs.json           Translator._track_cloud_cost session deltas

Output is deterministic (sorted keys, input order kept), so running it twice
gives byte-identical files. Regenerate deliberately after a server change.

Usage (from habla/):
    .venv/Scripts/python.exe scripts/gen_translate_goldens.py
"""

import json
import logging
import sys
from collections import defaultdict
from pathlib import Path
from types import SimpleNamespace

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from server import shared_assets  # noqa: E402
from server.config import lang_name, parse_direction  # noqa: E402
from server.models.prompts import (  # noqa: E402
    build_translator_user_prompt,
    get_passthrough_retry_prompt,
    get_quick_translate_prompt,
    get_topic_summary_prompt,
    get_translator_system_prompt,
)
from server.models.schemas import FlaggedPhrase  # noqa: E402
from server.pipeline.orchestrator import PipelineOrchestrator  # noqa: E402
from server.pipeline.translator import (  # noqa: E402
    Translator,
    _extract_field,
    _extract_raw_translation,
    _is_passthrough,
    _openai_request_body,
)
from server.services.idiom_scanner import IdiomScanner  # noqa: E402

REPO = Path(__file__).resolve().parent.parent.parent
GOLDEN_DIR = REPO / "android" / "translate" / "src" / "test" / "resources" / "golden"
INPUT_DIR = GOLDEN_DIR / "inputs"

# Same constant the Android Translator uses for every speaker field (single-speaker path).
SPEAKER_LABEL = "Speaker A"


def read_input(name: str):
    with open(INPUT_DIR / name, encoding="utf-8") as f:
        return json.load(f)


def write_golden(name: str, cases: list) -> None:
    if not cases:
        raise SystemExit(f"{name}: no cases produced")
    doc = {
        "_comment": "Generated by habla/scripts/gen_translate_goldens.py from the server code. Do not edit.",
        "cases": cases,
    }
    # allow_nan=False: NaN/Infinity are an accepted divergence and must not reach a golden.
    text = json.dumps(doc, ensure_ascii=False, indent=1, sort_keys=True, allow_nan=False) + "\n"
    with open(GOLDEN_DIR / name, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{name}: {len(cases)} cases")


def gen_parse() -> None:
    cases = []
    for item in read_input("raw_outputs.json"):
        try:
            # _parse_response never reads self.
            expected = Translator._parse_response(None, item["raw"], item["original"]).model_dump()
        except Exception as e:  # pydantic ValidationError, AttributeError, TypeError
            expected = {"invalid": True, "error": type(e).__name__}
        cases.append({"id": item["id"], "raw": item["raw"], "original": item["original"], "expected": expected})
    write_golden("parse.json", cases)


def gen_passthrough() -> None:
    cases = [
        {"source": s, "translated": t, "direction": d, "expected": _is_passthrough(s, t, d)}
        for s, t, d in read_input("passthrough.json")
    ]
    write_golden("passthrough.json", cases)


def gen_extract() -> None:
    data = read_input("extract.json")
    cases = [
        {"kind": "field", "text": text, "field": field, "expected": _extract_field(text, field)}
        for text, field in data["field"]
    ]
    cases += [
        {"kind": "raw", "text": text, "expected": _extract_raw_translation(text)}
        for text in data["raw"]
    ]
    write_golden("extract.json", cases)


def gen_request_bodies() -> None:
    data = read_input("request_bodies.json")
    models = list(shared_assets.models()["openai"]["models"].keys()) + data["extra_models"]
    cases = []
    for model in models:
        for call in data["calls"]:
            body = _openai_request_body(model, call["system"], call["user"], call["max_tokens"], call["json"])
            cases.append({"model": model, **call, "expected": body})
    write_golden("request_bodies.json", cases)


def gen_prompts() -> None:
    data = read_input("prompts.json")
    max_context = shared_assets.asr_profile()["context"]["max_context_exchanges"]
    cases = []
    for direction, mode in data["system"]:
        cases.append({
            "kind": "system", "direction": direction, "mode": mode,
            "expected": get_translator_system_prompt(direction, mode),
        })
    for item in data["user"]:
        exchanges = [
            {"speaker_label": SPEAKER_LABEL, "corrected": src, "translated": tr}
            for src, tr in item["context"]
        ]
        cases.append({
            "kind": "user", **item,
            "expected": build_translator_user_prompt(
                transcript=item["transcript"], speaker_label=SPEAKER_LABEL,
                context_exchanges=exchanges, topic_summary=item["topic"], max_context=max_context,
            ),
        })
    for text, direction in data["quick"]:
        src, tgt = parse_direction(direction)
        cases.append({
            "kind": "quick", "text": text, "direction": direction,
            "expected": get_quick_translate_prompt(text, lang_name(src), lang_name(tgt)),
        })
    for previous, source, translation in data["topic"]:
        cases.append({
            "kind": "topic", "previous": previous, "source": source, "translation": translation,
            "expected": get_topic_summary_prompt(previous, source, translation, SPEAKER_LABEL),
        })
    for transcript, direction in data["passthrough_retry"]:
        # Exactly what Translator._retry_passthrough builds.
        src, tgt = parse_direction(direction)
        cases.append({
            "kind": "passthrough_retry", "transcript": transcript, "direction": direction,
            "expected": get_passthrough_retry_prompt(transcript, lang_name(src), lang_name(tgt)),
        })
    write_golden("prompts.json", cases)


def gen_idioms() -> None:
    scanner = IdiomScanner()
    for path in shared_assets.idiom_files():
        scanner.load_from_json(path)
    stub = SimpleNamespace(_metrics=defaultdict(int))
    cases = []
    for item in read_input("idioms.json"):
        matches = scanner.scan(item["text"])
        llm = [FlaggedPhrase(**p) for p in item["llm"]]
        merged = PipelineOrchestrator._merge_idioms(stub, matches, llm)
        cases.append({
            "text": item["text"], "llm": item["llm"], "pattern_count": scanner.count,
            "scan": [
                {"canonical": m.canonical, "literal": m.literal, "meaning": m.meaning, "region": m.region,
                 "start": m.match_start, "end": m.match_end}
                for m in matches
            ],
            "expected": [fp.model_dump() for fp in merged],
        })
    write_golden("idioms.json", cases)


def gen_direction() -> None:
    data = read_input("direction.json")
    cases = []
    for setting in data["settings"]:
        for detected in data["detected"]:
            stub = SimpleNamespace(context_manager=SimpleNamespace(direction=setting))
            direction, _ = PipelineOrchestrator._resolve_effective_direction(stub, detected)
            cases.append({"setting": setting, "detected": detected, "expected": direction})
    write_golden("direction.json", cases)


def gen_costs() -> None:
    cases = []
    for item in read_input("costs.json"):
        stub = SimpleNamespace(
            _costs=defaultdict(float),
            config=SimpleNamespace(openai_model="", anthropic_model=""),
        )
        Translator._track_cloud_cost(
            stub, item["input"], item["output"], model=item["model"], provider="openai",
            cached_tokens=item["cached"],
        )
        cases.append({
            **item,
            "expected": {
                "session_cost_usd": stub._costs["session_cost_usd"],
                "session_input_tokens": stub._costs["session_input_tokens"],
                "session_output_tokens": stub._costs["session_output_tokens"],
            },
        })
    write_golden("costs.json", cases)


def main() -> None:
    logging.disable(logging.CRITICAL)  # the server functions log warnings for the malformed cases
    gen_parse()
    gen_passthrough()
    gen_extract()
    gen_request_bodies()
    gen_prompts()
    gen_idioms()
    gen_direction()
    gen_costs()


if __name__ == "__main__":
    main()
